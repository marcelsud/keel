// Package codegen generates unary NATS bindings and embeds the complete protobuf contract.
package codegen

import (
	"encoding/base64"
	"fmt"
	"path"
	"sort"
	"strconv"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"
)

const sdkPath = protogen.GoImportPath("github.com/marcelsud/keel/sdk")
const protoPath = protogen.GoImportPath("google.golang.org/protobuf/proto")
const contextPath = protogen.GoImportPath("context")
const errorsPath = protogen.GoImportPath("errors")

func Generate(request *pluginpb.CodeGeneratorRequest) (*pluginpb.CodeGeneratorResponse, error) {
	language := "go"
	for _, parameter := range strings.Split(request.GetParameter(), ",") {
		if key, value, _ := strings.Cut(parameter, "="); key == "lang" {
			language = value
		}
	}
	if language == "typescript" {
		// protogen needs Go import identities even when only TypeScript is emitted.
		// Parameter mappings preserve the language-neutral descriptors unchanged.
		request = proto.Clone(request).(*pluginpb.CodeGeneratorRequest)
		parameters := request.GetParameter()
		for _, file := range request.ProtoFile {
			if file.GetOptions().GetGoPackage() == "" {
				parameters += ",M" + file.GetName() + "=" + path.Join("keel.local/generated", path.Dir(file.GetName()))
			}
		}
		request.Parameter = proto.String(parameters)
	}
	plugin, err := (protogen.Options{ParamFunc: func(name, value string) error {
		if name != "lang" {
			return fmt.Errorf("unknown generator option %q", name)
		}
		language = value
		return nil
	}}).New(request)
	if err != nil {
		return nil, err
	}
	if language != "go" && language != "typescript" {
		return nil, fmt.Errorf("unsupported language %q", language)
	}
	plugin.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
	for _, file := range plugin.Files {
		if !file.Generate || len(file.Services) == 0 {
			continue
		}
		for _, service := range file.Services {
			for _, method := range service.Methods {
				if method.Desc.IsStreamingClient() || method.Desc.IsStreamingServer() {
					return nil, fmt.Errorf("streaming RPC %s is not supported", method.Desc.FullName())
				}
			}
		}
		bundle, err := descriptorBundle(file.Proto.GetName(), request.ProtoFile)
		if err != nil {
			return nil, err
		}
		encoded := base64.StdEncoding.EncodeToString(bundle)
		if language == "go" {
			generateGo(plugin, file, encoded)
		} else {
			generateTypeScript(plugin, file, encoded)
		}
	}
	return plugin.Response(), nil
}

func descriptorBundle(root string, files []*descriptorpb.FileDescriptorProto) ([]byte, error) {
	byName := make(map[string]*descriptorpb.FileDescriptorProto)
	for _, file := range files {
		byName[file.GetName()] = file
	}
	seen := make(map[string]bool)
	set := new(descriptorpb.FileDescriptorSet)
	var visit func(string) error
	visit = func(name string) error {
		if seen[name] {
			return nil
		}
		seen[name] = true
		file := byName[name]
		if file == nil {
			return fmt.Errorf("missing descriptor dependency %q", name)
		}
		dependencies := append([]string(nil), file.Dependency...)
		sort.Strings(dependencies)
		for _, dependency := range dependencies {
			if err := visit(dependency); err != nil {
				return err
			}
		}
		copy := proto.Clone(file).(*descriptorpb.FileDescriptorProto)
		copy.SourceCodeInfo = nil
		set.File = append(set.File, copy)
		return nil
	}
	if err := visit(root); err != nil {
		return nil, err
	}
	return proto.MarshalOptions{Deterministic: true}.Marshal(set)
}

func generateGo(plugin *protogen.Plugin, file *protogen.File, schema string) {
	g := plugin.NewGeneratedFile(file.GeneratedFilenamePrefix+".keel.go", file.GoImportPath)
	g.P("// Code generated by protoc-gen-keel. DO NOT EDIT.")
	g.P("package ", file.GoPackageName)
	for _, service := range file.Services {
		name := service.GoName
		g.P("var ", name, "Contract = ", sdkPath.Ident("Contract"), "{")
		g.P("Service: ", strconv.Quote(string(service.Desc.FullName())), ",")
		g.P("Schema: ", strconv.Quote(schema), ",")
		g.P("}")
		g.P("type ", name, "Server interface {")
		for _, method := range service.Methods {
			g.P(method.GoName, "(ctx *", sdkPath.Ident("Context"), ", request *", method.Input.GoIdent, ") (*", method.Output.GoIdent, ", error)")
		}
		g.P("}")
		g.P("func Register", name, "(app *", sdkPath.Ident("App"), ", implementation ", name, "Server, options ", sdkPath.Ident("ContractOptions"), ") error {")
		g.P("if implementation == nil && options.State != ", sdkPath.Ident("Retired"), " { return ", errorsPath.Ident("New"), "(\"service implementation is required\") }")
		g.P("return app.RegisterProtobuf(", name, "Contract, map[string]", sdkPath.Ident("ProtobufMethod"), "{")
		for _, method := range service.Methods {
			g.P(strconv.Quote(string(method.Desc.Name())), ": {")
			g.P("NewInput: func() ", protoPath.Ident("Message"), " { return new(", method.Input.GoIdent, ") },")
			g.P("Handler: func(ctx *", sdkPath.Ident("Context"), ", input ", protoPath.Ident("Message"), ") (", protoPath.Ident("Message"), ", error) {")
			g.P("return implementation.", method.GoName, "(ctx, input.(*", method.Input.GoIdent, "))")
			g.P("}, },")
		}
		g.P("}, options)")
		g.P("}")
		g.P("type ", name, "Client struct { app ", sdkPath.Ident("ProtobufCaller"), " }")
		g.P("func New", name, "Client(app ", sdkPath.Ident("ProtobufCaller"), ") *", name, "Client { return &", name, "Client{app: app} }")
		for _, method := range service.Methods {
			g.P("func (client *", name, "Client) ", method.GoName, "(ctx ", contextPath.Ident("Context"), ", input *", method.Input.GoIdent, ") (*", method.Output.GoIdent, ", error) {")
			g.P("output := new(", method.Output.GoIdent, ")")
			g.P("if err := client.app.CallProtobuf(ctx, ", strconv.Quote(string(service.Desc.FullName())), ", ", strconv.Quote(string(method.Desc.Name())), ", input, output); err != nil { return nil, err }")
			g.P("return output, nil")
			g.P("}")
		}
	}
}

func generateTypeScript(plugin *protogen.Plugin, file *protogen.File, schema string) {
	g := plugin.NewGeneratedFile(file.GeneratedFilenamePrefix+"_keel.ts", file.GoImportPath)
	g.P("// Code generated by protoc-gen-keel. DO NOT EDIT.")
	for _, service := range file.Services {
		name := service.GoName
		g.P("import { ", name, " } from ", strconv.Quote("./"+path.Base(file.GeneratedFilenamePrefix)+"_pb.js"), ";")
		g.P("export const ", name, "Contract = { service: ", name, ", schema: ", strconv.Quote(schema), " };")
	}
}
